// 查表 exp: x in (-inf, 0]。tab 為切 bank 後的本地 ROM 副本。
static inline data_t lut_exp(const data_t tab[EXP_TSIZE], data_t x) {
    #pragma HLS INLINE
    if (x <= (data_t)EXP_XMIN_F) return tab[0];
    if (x >= (data_t)0)          return tab[EXP_TSIZE - 1];
    data_t t = (data_t)1 - x / (data_t)EXP_XMIN_F;   // t in (0,1)
    int idx = (int)(t * (EXP_TSIZE - 1));
    if (idx < 0) idx = 0;
    if (idx >= EXP_TSIZE) idx = EXP_TSIZE - 1;
    return tab[idx];
}

void attention_head(
    data_t Q[N][DK],
    data_t K[N][DK],
    data_t V[N][DK],
    data_t O[N][DK])
{
    #pragma HLS ARRAY_PARTITION variable=Q complete dim=2
    #pragma HLS ARRAY_PARTITION variable=K cyclic factor=16 dim=2
    #pragma HLS ARRAY_PARTITION variable=V complete dim=2

    // 把編譯期常數表複製到本地 FP16 ROM, 切 4 bank 支援 u4 並行查詢。
    // 唯讀 + 常數初始化 -> Vitis 推斷為 ROM (無 DSP, 無 exp 電路)。
    data_t exp_tab[EXP_TSIZE];
    #pragma HLS ARRAY_PARTITION variable=exp_tab cyclic factor=4 dim=1
    Init_ROM: for (int t = 0; t < EXP_TSIZE; t++) {
        #pragma HLS UNROLL factor=4
        exp_tab[t] = (data_t)EXP_ROM[t];
    }

    data_t S_row[N];

    Row_Loop: for (int i = 0; i < N; i++) {

        // ===== 1) S = Q.K^T : factor=16 + 加法樹 (同 S7) =====
        QKt_Loop: for (int j = 0; j < N; j++) {
            #pragma HLS PIPELINE II=1
            data_t ps[8];
            #pragma HLS ARRAY_PARTITION variable=ps complete dim=1
            Group_K: for (int g = 0; g < 8; g++) {
                #pragma HLS UNROLL
                data_t s = (data_t)0;
                Inner_K: for (int kk = 0; kk < QK_BANKS; kk++) {
                    #pragma HLS UNROLL
                    s += Q[i][g*QK_BANKS+kk] * K[j][g*QK_BANKS+kk];
                }
                ps[g] = s;
            }
            data_t group_sum = ((ps[0] + ps[1]) + (ps[2] + ps[3]))
                             + ((ps[4] + ps[5]) + (ps[6] + ps[7]));
            S_row[j] = (data_t)(group_sum * INV_SQRT_DK);
        }

        // ===== 2a) Max =====
        data_t max_v = S_row[0];
        Max_Loop: for (int j = 1; j < N; j++) {
            #pragma HLS PIPELINE II=1
            if (S_row[j] > max_v) max_v = S_row[j];
        }

        // ===== 2b) Exp (查表!) + Sum : softmax u4 =====
        data_t denom0 = (data_t)0, denom1 = (data_t)0;
        data_t denom2 = (data_t)0, denom3 = (data_t)0;
        Exp_Loop: for (int j = 0; j < N; j += 4) {
            #pragma HLS PIPELINE II=1
            data_t e0 = lut_exp(exp_tab, (data_t)(S_row[j]   - max_v));
            data_t e1 = lut_exp(exp_tab, (data_t)(S_row[j+1] - max_v));
            data_t e2 = lut_exp(exp_tab, (data_t)(S_row[j+2] - max_v));
            data_t e3 = lut_exp(exp_tab, (data_t)(S_row[j+3] - max_v));
            S_row[j]   = e0;  S_row[j+1] = e1;
            S_row[j+2] = e2;  S_row[j+3] = e3;
            denom0 += e0;  denom1 += e1;
            denom2 += e2;  denom3 += e3;
        }
        data_t denom = (denom0 + denom1) + (denom2 + denom3);

        // ===== 2c) Norm =====
        data_t inv_denom = (data_t)((data_t)1 / denom);
        Norm_Loop: for (int j = 0; j < N; j++) {
            #pragma HLS PIPELINE II=1
            S_row[j] = S_row[j] * inv_denom;
        }

        // ===== 3) O = P.V : 完全展開 (同 S7) =====
        data_t acc[DK];
        #pragma HLS ARRAY_PARTITION variable=acc complete dim=1
        Init_Acc: for (int d = 0; d < DK; d++) {
            #pragma HLS UNROLL
            acc[d] = (data_t)0;
        }
        PV_Loop: for (int j = 0; j < N; j++) {
            #pragma HLS PIPELINE II=1
            data_t p = S_row[j];
            MAC_D: for (int d = 0; d < DK; d++) {
                #pragma HLS UNROLL
                acc[d] += p * V[j][d];
            }
        }
        Write_O: for (int d = 0; d < DK; d++) {
            #pragma HLS UNROLL
            O[i][d] = (data_t)acc[d];
        }
    }
}