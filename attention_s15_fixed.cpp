// ---- per-tensor 定點格式 (12-bit + 查表 exp, 4 seed PASS max_abs 0.0021) ----
typedef ap_fixed<12,1>  io_t;     // Q,K,V,O: [-1,1), 11 frac
typedef ap_fixed<16,1>  p_t;      // P 權重: 正規化後 ~0.001, 16-bit
typedef ap_fixed<12,3>  s_t;      // S 值: [-4,4)
typedef ap_fixed<32,8>  qkacc_t;  // QKt 累加器
typedef ap_fixed<32,8>  pvacc_t;  // PV 累加器
typedef ap_fixed<24,12> den_t;    // softmax 分母: 裝得下 ~N=1024
typedef ap_fixed<24,1>  inv_t;    // 1/denom

static const s_t INV_SQRT_DK = (s_t)0.08838834764831845f;

// 查表 exp: x in (-inf,0], 回傳 p_t。
// 最穩健寫法: 索引完全用 float/int, 避免 ap_fixed 算術的範圍陷阱。
// 表: i=0 -> x=-16, i=TSIZE-1 -> x=0。線性映射 x -> idx。
static inline p_t lut_exp(const p_t tab[EXP_TSIZE], s_t x_fixed) {
    #pragma HLS INLINE
    float x = (float)x_fixed;               // 轉 float, 脫離定點範圍限制
    if (x <= -16.0f) return tab[0];
    if (x >= 0.0f)   return tab[EXP_TSIZE - 1];
    // x in (-16,0): idx = (x+16)/16 * (TSIZE-1)
    float pos = (x + 16.0f) * (float)(EXP_TSIZE - 1) / 16.0f;
    int idx = (int)pos;
    if (idx < 0) idx = 0;
    if (idx >= EXP_TSIZE) idx = EXP_TSIZE - 1;
    return tab[idx];
}

void attention_head(
    io_t Q[N][DK],
    io_t K[N][DK],
    io_t V[N][DK],
    io_t O[N][DK])
{
    #pragma HLS ARRAY_PARTITION variable=Q complete dim=2
    #pragma HLS ARRAY_PARTITION variable=K cyclic factor=16 dim=2
    #pragma HLS ARRAY_PARTITION variable=V complete dim=2

    // exp 查表 ROM (改 static 避免 C-sim stack 問題)
    static p_t exp_tab[EXP_TSIZE];
    #pragma HLS ARRAY_PARTITION variable=exp_tab cyclic factor=4 dim=1
    Init_ROM: for (int t = 0; t < EXP_TSIZE; t++) {
        #pragma HLS UNROLL factor=4
        exp_tab[t] = (p_t)EXP_ROM[t];
    }

    static s_t S_row[N];
    static p_t P_row[N];

    Row_Loop: for (int i = 0; i < N; i++) {

        // ===== 1) S = Q.K^T : factor=16 + 加法樹 =====
        QKt_Loop: for (int j = 0; j < N; j++) {
            #pragma HLS PIPELINE II=1
            qkacc_t ps[8];
            #pragma HLS ARRAY_PARTITION variable=ps complete dim=1
            Group_K: for (int g = 0; g < 8; g++) {
                #pragma HLS UNROLL
                qkacc_t s = (qkacc_t)0;
                Inner_K: for (int kk = 0; kk < QK_BANKS; kk++) {
                    #pragma HLS UNROLL
                    s += (qkacc_t)(Q[i][g*QK_BANKS+kk] * K[j][g*QK_BANKS+kk]);
                }
                ps[g] = s;
            }
            qkacc_t group_sum = ((ps[0] + ps[1]) + (ps[2] + ps[3]))
                              + ((ps[4] + ps[5]) + (ps[6] + ps[7]));
            S_row[j] = (s_t)(group_sum * INV_SQRT_DK);
        }

        // ===== 2a) Max =====
        s_t max_v = S_row[0];
        Max_Loop: for (int j = 1; j < N; j++) {
            #pragma HLS PIPELINE II=1
            if (S_row[j] > max_v) max_v = S_row[j];
        }

        // ===== 2b) Exp (查表) + Sum : softmax u4 =====
        den_t denom0 = (den_t)0, denom1 = (den_t)0;
        den_t denom2 = (den_t)0, denom3 = (den_t)0;
        Exp_Loop: for (int j = 0; j < N; j += 4) {
            #pragma HLS PIPELINE II=1
            p_t e0 = lut_exp(exp_tab, (s_t)(S_row[j]   - max_v));
            p_t e1 = lut_exp(exp_tab, (s_t)(S_row[j+1] - max_v));
            p_t e2 = lut_exp(exp_tab, (s_t)(S_row[j+2] - max_v));
            p_t e3 = lut_exp(exp_tab, (s_t)(S_row[j+3] - max_v));
            P_row[j]   = e0;  P_row[j+1] = e1;
            P_row[j+2] = e2;  P_row[j+3] = e3;
            denom0 += e0;  denom1 += e1;
            denom2 += e2;  denom3 += e3;
        }
        den_t denom = (denom0 + denom1) + (denom2 + denom3);

        // ===== 2c) Norm =====
        inv_t inv_denom = (inv_t)((float)1.0f / (float)denom);
        Norm_Loop: for (int j = 0; j < N; j++) {
            #pragma HLS PIPELINE II=1
            P_row[j] = (p_t)(P_row[j] * inv_denom);
        }

        // ===== 3) O = P.V : 完全展開 =====
        pvacc_t acc[DK];
        #pragma HLS ARRAY_PARTITION variable=acc complete dim=1
        Init_Acc: for (int d = 0; d < DK; d++) {
            #pragma HLS UNROLL
            acc[d] = (pvacc_t)0;
        }
        PV_Loop: for (int j = 0; j < N; j++) {
            #pragma HLS PIPELINE II=1
            p_t p = P_row[j];
            MAC_D: for (int d = 0; d < DK; d++) {
                #pragma HLS UNROLL
                acc[d] += (pvacc_t)(p * V[j][d]);
            }
        }
        Write_O: for (int d = 0; d < DK; d++) {
            #pragma HLS UNROLL
            O[i][d] = (io_t)acc[d];
        }
    }
}